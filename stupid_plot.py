# ---------- utils ----------
def parse_raw(raw: str) -> pd.DataFrame:
    rows = []
    rdr = csv.reader(io.StringIO(raw), delimiter=',')
    for parts in rdr:
        # salta righe vuote o commenti
        if (not parts) or (parts[0].strip().startswith('#')): 
            continue
        if len(parts) < 6:
            continue
        act, t, olat, olon, nlat, nlon = [p.strip() for p in parts[:6]]
        rows.append({
            "ActivityId": act,
            "Time": t,
            "OLD_Latitude": float(olat.replace(',', '.')),
            "OLD_Longitude": float(olon.replace(',', '.')),
            "NEW_Latitude": float(nlat.replace(',', '.')) if nlat not in (None, "", "NaN") else None,
            "NEW_Longitude": float(nlon.replace(',', '.')) if nlon not in (None, "", "NaN") else None,
        })
    return pd.DataFrame(rows)

def to_coords(df: pd.DataFrame, lat: str, lon: str) -> List[Tuple[float,float]]:
    sub = df[[lat, lon]].dropna()
    return list(map(tuple, sub.values.tolist()))

def bounds(coords: List[Tuple[float,float]]):
    lats = [c[0] for c in coords]
    lons = [c[1] for c in coords]
    return min(lats), min(lons), max(lats), max(lons)

# ---------- main ----------
def main():
    df = parse_raw(RAW)
    old_coords = to_coords(df, "OLD_Latitude", "OLD_Longitude")
    new_coords = to_coords(df.dropna(subset=["NEW_Latitude", "NEW_Longitude"]), "NEW_Latitude", "NEW_Longitude")

    if not old_coords and not new_coords:
        raise ValueError("Nessuna coordinata valida in RAW.")

    # bbox per zoom fit
    allc = old_coords + new_coords
    minlat, minlon, maxlat, maxlon = bounds(allc)
    center = [(minlat + maxlat) / 2.0, (minlon + maxlon) / 2.0]

    # Basemap “vera” con nomi delle vie
    m = folium.Map(location=center, zoom_start=16, tiles="OpenStreetMap", control_scale=True)

    # Traccia OLD (rosso)
    if len(old_coords) >= 2:
        folium.PolyLine(old_coords, color="red", weight=5, opacity=0.9, tooltip="OLD").add_to(m)
        folium.Marker(old_coords[0], tooltip="OLD start", icon=folium.Icon(color="red")).add_to(m)
        folium.Marker(old_coords[-1], tooltip="OLD end", icon=folium.Icon(color="red")).add_to(m)
    elif len(old_coords) == 1:
        folium.Marker(old_coords[0], tooltip="OLD point", icon=folium.Icon(color="red")).add_to(m)

    # Traccia NEW (blu)
    if len(new_coords) >= 2:
        folium.PolyLine(new_coords, color="blue", weight=5, opacity=0.9, tooltip="NEW").add_to(m)
        folium.Marker(new_coords[0], tooltip="NEW start", icon=folium.Icon(color="blue")).add_to(m)
        folium.Marker(new_coords[-1], tooltip="NEW end", icon=folium.Icon(color="blue")).add_to(m)
    elif len(new_coords) == 1:
        folium.Marker(new_coords[0], tooltip="NEW point", icon=folium.Icon(color="blue")).add_to(m)

    m.fit_bounds([[minlat, minlon], [maxlat, maxlon]])
    m.save(OUT_HTML)
    print(f"Salvato: {OUT_HTML}")

if __name__ == "__main__":
    main()
